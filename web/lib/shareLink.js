/**
 * ลิงก์ที่ "ส่งออกไปให้คนนอกกด" (แปะใน LINE / Discord / แชตอะไรก็ตาม) ต้องผ่านตัวนี้เสมอ
 *
 * ปัญหา: LINE เปิดลิงก์ในมินิเบราว์เซอร์ของตัวเองเสมอ ซึ่ง
 *   - cookie ไม่อยู่ยาว → ปิดแล้วเปิดใหม่ต้องล็อกอินซ้ำทุกครั้ง
 *   - OAuth เด้งออกไปโดเมนอื่นแล้ว callback หลงทาง (Discord เด้งไปเปิดแอปตัวเอง)
 *   - Google บล็อก embedded webview ตรงๆ (disallowed_useragent) = กดไม่ได้เลย
 * เคสจริง: ส่งลิงก์เซ็นเอกสารให้ผู้รับเงิน แล้วต้องคอยบอกให้ก๊อป URL ไปแปะใน Chrome เอง
 *
 * `openExternalBrowser=1` เป็นพารามิเตอร์ทางการของ LINE — สั่งให้เปิดเบราว์เซอร์หลัก
 * ของเครื่องแทนมินิเบราว์เซอร์ ได้ทั้ง iOS และ Android
 *
 * แอปอื่นไม่รู้จัก param นี้ = ถูกเมินเฉยๆ ไม่มีผลข้างเคียง และไม่มีหน้าไหนในระบบอ่าน query ชื่อนี้
 * (Facebook/IG ไม่มีท่าแบบนี้ให้ใช้ — ต้องแก้ที่ฝั่งหน้าเว็บ ไม่ใช่ที่ลิงก์)
 */
export function externalBrowserUrl(url) {
  return `${url}${url.includes('?') ? '&' : '?'}openExternalBrowser=1`
}
