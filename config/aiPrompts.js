/** ประกอบ head + format + tail เป็น prompt เดียว — ส่วนไหนว่างข้ามไป ไม่เว้นบรรทัดเกิน */
function assemble(head, format, tail) {
  return [head, format, tail].filter(Boolean).join('\n\n');
}

const bySlot = new Map(AI_PROMPTS.map(p => [p.value, p]));

/** ทุกส่วนของช่องนี้ (head/format/tail แยก) — ใช้โดย backoffice · null ถ้าไม่รู้จัก */
function defaultParts(value) {
  const p = bySlot.get(value);
  if (!p) return null;
  return { head: p.head || '', format: p.format || '', tail: p.tail || '', requiredKeys: p.requiredKeys, label: p.label, surface: p.surface };
}

/** prompt เต็มที่ประกอบแล้ว — ใช้เป็น fallback ตอนยิง AI จริง · null ถ้าไม่รู้จัก */
function defaultPrompt(value) {
  const p = defaultParts(value);
  return p ? assemble(p.head, p.format, p.tail) : null;
}

